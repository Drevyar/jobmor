-- JobMor authentication and profile foundation.
-- Public registration accepts only student and employer roles.
-- Admin creation is a one-time server-side operation; never expose service_role to the app.

create type public.app_role as enum ('student', 'employer', 'admin');
create type public.verification_status as enum ('pending_email', 'verified', 'suspended');

create table public.business_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name_en text not null,
  name_th text not null,
  created_at timestamptz not null default now()
);

